//! Pull request detail, discussion threads, changed files and per-file diffs (read-only).
//!
//! Pure mapping and diffing live at the top of this module so they can be unit tested
//! with fixtures; the Tauri commands at the bottom only orchestrate HTTP calls.
//! Markdown (descriptions, comments) is rendered and sanitized here; file contents are
//! returned as plain text and must be rendered as text nodes by the webview.

