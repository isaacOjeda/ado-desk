/// Each side of a diff is capped; beyond it the UI points to the web instead.
pub const MAX_DIFF_SIDE_BYTES: usize = 512 * 1024;
const DIFF_CONTEXT_LINES: usize = 3;
const DIFF_TIMEOUT: Duration = Duration::from_secs(2);
const MAX_CHANGES: &str = "2000";
const LINKED_WORK_ITEM_FIELDS: &str =
    "System.Title,System.WorkItemType,System.State,System.TeamProject";

