#[tauri::command]
pub async fn get_pull_request(
    state: State<'_, AppState>,
    project: String,
    repository_id: String,
    id: i64,
) -> AppResult<PullRequestDetail> {
    let client = current_client(&state)?;
    let detail_url = pr_url(&client, &project, &repository_id, id, &[]);
    let (raw, work_items) = futures::join!(
        client.get_json::<RawPullRequestDetail>(detail_url),
        linked_work_items(&client, &project, &repository_id, id)
    );
    // Linked work items are secondary: show the pull request even if they fail.
    Ok(map_detail(client.org(), raw?, work_items.unwrap_or_default()))
}

