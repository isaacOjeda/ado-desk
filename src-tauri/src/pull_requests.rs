#[tauri::command]
pub async fn list_pull_request_files(
    state: State<'_, AppState>,
    project: String,
    repository_id: String,
    id: i64,
) -> AppResult<PullRequestFiles> {
    let client = current_client(&state)?;
    let iterations: ListResponse<RawIteration> = client
        .get_json(pr_url(&client, &project, &repository_id, id, &["iterations"]))
        .await?;
    let Some(latest) = iterations.value.iter().map(|i| i.id).max() else {
        return Ok(PullRequestFiles { iteration_id: None, files: Vec::new(), truncated: false });
    };

    let latest_str = latest.to_string();
    let mut url = pr_url(&client, &project, &repository_id, id, &["iterations", &latest_str, "changes"]);
    // compareTo=0 compares against the merge base, like the web "Files" tab.
    url.query_pairs_mut()
        .append_pair("$top", MAX_CHANGES)
        .append_pair("$compareTo", "0");
    let raw: RawIterationChanges = client.get_json(url).await?;

    let mut files = map_changes(raw);
    files.iteration_id = Some(latest);
    Ok(files)
}

/// Diff of one changed file. Blob ids come from [`list_pull_request_files`].
#[tauri::command]
pub async fn get_pull_request_file_diff(
    state: State<'_, AppState>,
    project: String,
    repository_id: String,
    object_id: Option<String>,
    original_object_id: Option<String>,
) -> AppResult<FileDiff> {
    let new_sha = valid_object_id(object_id.as_deref());
    let old_sha = valid_object_id(original_object_id.as_deref());
    // A sha that was sent but is malformed is rejected before any URL is built.
    let malformed = |sent: &Option<String>, valid: &Option<String>| {
        sent.as_deref().is_some_and(|s| !s.is_empty() && !is_zero_sha(s)) && valid.is_none()
    };
    if malformed(&object_id, &new_sha) || malformed(&original_object_id, &old_sha) {
        return Err(AppError::NotFound);
    }

    let client = current_client(&state)?;
    let (old, new) = futures::try_join!(
        blob(&client, &project, &repository_id, old_sha.as_deref()),
        blob(&client, &project, &repository_id, new_sha.as_deref())
    )?;

    let (old, new) = match (old, new) {
        (Blob::TooLarge, _) | (_, Blob::TooLarge) => {
            return Ok(FileDiff { too_large: true, ..FileDiff::default() });
        }
        (old, new) => (old.into_bytes(), new.into_bytes()),
    };
    // Diffing up to 2 x 512 KB is CPU work: keep it off the async workers.
    tauri::async_runtime::spawn_blocking(move || build_file_diff(old.as_deref(), new.as_deref()))
        .await
        .map_err(|err| AppError::Decode(err.to_string()))
}

impl Blob {
    fn into_bytes(self) -> Option<Vec<u8>> {
        match self {
            Blob::Bytes(bytes) => Some(bytes),
            Blob::Missing | Blob::TooLarge => None,
        }
    }
}

fn is_zero_sha(sha: &str) -> bool {
    sha.chars().all(|c| c == '0')
}

