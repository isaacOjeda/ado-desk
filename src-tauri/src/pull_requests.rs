    fn rows(diff: &FileDiff) -> Vec<(Option<usize>, Option<usize>, &str)> {
        diff.hunks
            .iter()
            .flat_map(|h| h.lines.iter())
            .map(|l| (l.old_line, l.new_line, l.text.as_str()))
            .collect()
    }

