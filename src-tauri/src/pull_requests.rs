#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum PullRequestStatus {
    Active,
    Draft,
    Completed,
    Abandoned,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Reviewer {
    pub id: String,
    pub name: String,
    /// 10 approved, 5 approved with suggestions, 0 no vote, -5 waiting for author, -10 rejected.
    pub vote: i64,
    pub is_required: bool,
    pub has_declined: bool,
    /// Groups and teams added as reviewers.
    pub is_group: bool,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct PullRequestDetail {
    pub id: i64,
    pub title: String,
    /// Sanitized HTML rendered from the Markdown description. Empty when there is none.
    pub description_html: String,
    pub status: PullRequestStatus,
    pub is_draft: bool,
    pub author: String,
    pub created_at: String,
    pub closed_at: Option<String>,
    pub source_branch: String,
    pub target_branch: String,
    /// Raw Azure DevOps merge status (`succeeded`, `conflicts`, `queued`, ...), if known.
    pub merge_status: Option<String>,
    pub repository: String,
    pub project: String,
    pub reviewers: Vec<Reviewer>,
    pub labels: Vec<String>,
    pub work_items: Vec<WorkItem>,
    pub url: String,
}

#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum ThreadKind {
    /// Discussion on the pull request itself.
    General,
    /// Comments anchored to a file (and usually a line).
    File,
    /// Activity generated by Azure DevOps (votes, pushes, status changes).
    System,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct ThreadComment {
    pub id: i64,
    pub parent_id: Option<i64>,
    pub author: String,
    pub published_at: Option<String>,
    pub updated_at: Option<String>,
    /// Sanitized HTML for user comments; empty for system comments.
    pub html: String,
    /// Plain text for system comments (render as a text node, never as HTML).
    pub text: Option<String>,
    pub is_system: bool,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct PullRequestThread {
    pub id: i64,
    pub kind: ThreadKind,
    /// `active`, `fixed`, `wontFix`, `closed`, `byDesign`, `pending`; `None` for activity.
    pub status: Option<String>,
    pub published_at: Option<String>,
    pub file_path: Option<String>,
    pub right_line: Option<i64>,
    pub left_line: Option<i64>,
    pub comments: Vec<ThreadComment>,
}

#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum FileChangeType {
    Add,
    Edit,
    Delete,
    Rename,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct FileChange {
    pub path: String,
    pub original_path: Option<String>,
    pub change_type: FileChangeType,
    /// Blob of the new side; `None` for deletions.
    pub object_id: Option<String>,
    /// Blob of the old side; `None` for additions.
    pub original_object_id: Option<String>,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct PullRequestFiles {
    pub iteration_id: Option<i64>,
    pub files: Vec<FileChange>,
    /// True when Azure DevOps reported more changes than were fetched.
    pub truncated: bool,
}

#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum DiffLineKind {
    Context,
    Add,
    Delete,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct DiffLine {
    pub kind: DiffLineKind,
    pub old_line: Option<usize>,
    pub new_line: Option<usize>,
    pub text: String,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct DiffHunk {
    pub old_start: usize,
    pub old_lines: usize,
    pub new_start: usize,
    pub new_lines: usize,
    pub lines: Vec<DiffLine>,
}

#[derive(Debug, Clone, Default, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct FileDiff {
    pub hunks: Vec<DiffHunk>,
    pub additions: usize,
    pub deletions: usize,
    pub binary: bool,
    pub too_large: bool,
}

