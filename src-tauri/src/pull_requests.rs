/// Binary when it contains a NUL byte or is not valid UTF-8.
pub fn decode_text(bytes: &[u8]) -> Option<&str> {
    if bytes.contains(&0) {
        return None;
    }
    let text = std::str::from_utf8(bytes).ok()?;
    Some(text.strip_prefix('\u{feff}').unwrap_or(text))
}

/// Builds unified hunks (3 lines of context) between two optional file versions.
/// `None` means the side does not exist (added or deleted file).
pub fn build_file_diff(old: Option<&[u8]>, new: Option<&[u8]>) -> FileDiff {
    let too_large = |side: Option<&[u8]>| side.is_some_and(|b| b.len() > MAX_DIFF_SIDE_BYTES);
    if too_large(old) || too_large(new) {
        return FileDiff { too_large: true, ..FileDiff::default() };
    }
    let (Some(old_text), Some(new_text)) = (old.map_or(Some(""), decode_text), new.map_or(Some(""), decode_text))
    else {
        return FileDiff { binary: true, ..FileDiff::default() };
    };

    let diff = TextDiff::configure().timeout(DIFF_TIMEOUT).diff_lines(old_text, new_text);
    let mut result = FileDiff::default();

    for group in diff.grouped_ops(DIFF_CONTEXT_LINES) {
        let (Some(first), Some(last)) = (group.first(), group.last()) else { continue };
        let old_range = first.old_range().start..last.old_range().end;
        let new_range = first.new_range().start..last.new_range().end;

        let mut lines = Vec::new();
        for op in &group {
            for change in diff.iter_changes(op) {
                let kind = match change.tag() {
                    ChangeTag::Equal => DiffLineKind::Context,
                    ChangeTag::Delete => {
                        result.deletions += 1;
                        DiffLineKind::Delete
                    }
                    ChangeTag::Insert => {
                        result.additions += 1;
                        DiffLineKind::Add
                    }
                };
                let value = change.value();
                let text = value.strip_suffix('\n').unwrap_or(value);
                let text = text.strip_suffix('\r').unwrap_or(text);
                lines.push(DiffLine {
                    kind,
                    old_line: change.old_index().map(|i| i + 1),
                    new_line: change.new_index().map(|i| i + 1),
                    text: text.to_string(),
                });
            }
        }

        // Unified diff convention: an empty range starts at the line before it.
        let start = |range: &std::ops::Range<usize>| if range.is_empty() { range.start } else { range.start + 1 };
        result.hunks.push(DiffHunk {
            old_start: start(&old_range),
            old_lines: old_range.len(),
            new_start: start(&new_range),
            new_lines: new_range.len(),
            lines,
        });
    }

    result
}

