fn pr_url(client: &AzdoClient, project: &str, repository_id: &str, id: i64, tail: &[&str]) -> url::Url {
    let id = id.to_string();
    let mut segments = vec![project, "_apis", "git", "repositories", repository_id, "pullRequests", &id];
    segments.extend_from_slice(tail);
    client.url(&segments)
}

async fn linked_work_items(client: &AzdoClient, project: &str, repository_id: &str, id: i64) -> AppResult<Vec<WorkItem>> {
    let refs: ListResponse<RawResourceRef> = client
        .get_json(pr_url(client, project, repository_id, id, &["workitems"]))
        .await?;
    let ids: Vec<String> = refs
        .value
        .into_iter()
        .filter(|r| r.id.chars().all(|c| c.is_ascii_digit()) && !r.id.is_empty())
        .map(|r| r.id)
        .take(200)
        .collect();
    if ids.is_empty() {
        return Ok(Vec::new());
    }

    let mut url = client.url(&["_apis", "wit", "workitems"]);
    url.query_pairs_mut()
        .append_pair("ids", &ids.join(","))
        .append_pair("fields", LINKED_WORK_ITEM_FIELDS)
        .append_pair("errorPolicy", "Omit");
    let items: ListResponse<Option<RawWorkItem>> = client.get_json(url).await?;
    Ok(items
        .value
        .into_iter()
        .flatten()
        .map(|raw| model::map_work_item(client.org(), raw))
        .collect())
}

enum Blob {
    Missing,
    TooLarge,
    Bytes(Vec<u8>),
}

async fn blob(client: &AzdoClient, project: &str, repository_id: &str, sha: Option<&str>) -> AppResult<Blob> {
    let Some(sha) = sha else { return Ok(Blob::Missing) };
    let segments = [project, "_apis", "git", "repositories", repository_id, "blobs", sha];

    // Ask for the size first so huge files are never downloaded.
    let mut meta_url = client.url(&segments);
    meta_url.query_pairs_mut().append_pair("$format", "json");
    let meta: RawBlobRef = client.get_json(meta_url).await?;
    if meta.size > MAX_DIFF_SIDE_BYTES as u64 {
        return Ok(Blob::TooLarge);
    }

    let mut url = client.url(&segments);
    url.query_pairs_mut().append_pair("$format", "octetstream");
    let (bytes, _) = client.get_bytes(url).await?;
    Ok(Blob::Bytes(bytes))
}

